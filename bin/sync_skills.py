#!/usr/bin/env python3
"""Publish the skills in this repo to every local model.  Run after adding or editing a skill:

  python3 ~/Desktop/github_repos/local-rig-skills/bin/sync_skills.py          # INDEX.md + Open WebUI + prompts
  python3 ~/Desktop/github_repos/local-rig-skills/bin/sync_skills.py --check  # only validate the SKILL.md files

What it does:
  1. validates skills/*/SKILL.md (front matter with name + description, name == folder, size limit)
  2. writes INDEX.md (the catalog, also read by sync_prompts.py for the system prompts)
  3. Open WebUI (native Skills, 0.12+): creates/updates one skill per folder (id = name) - every model with native
     tools sees the list and loads a skill with its `view_skill` tool; users can also pick one with `$` in the chat
  4. adds every skill to the "/" prompt menu of the Open WebUI chat box (autocomplete: type "/dow..." -> /download-llm)
  5. runs ~/.config/llama-swap/tools/sync_prompts.py, which puts the catalog into every model's system prompt
     (Open WebUI and the llama.cpp chat UI), so "/skill-name ..." works in both UIs
"""
import json, pathlib, re, subprocess, sys

REPO = pathlib.Path(__file__).resolve().parents[1]
SKILLS = REPO / "skills"
TAG = "local-rig-skills"
MAX_CHARS = 10000          # hard cap per SKILL.md (reference/skill-format.md); Open WebUI's own limit is 20k
TARGET_CHARS = 6000        # ~1,500 tokens: above this, move detail into a reference file
MAX_DESC = 300             # the description is in every system prompt and OpenClaw's skill list


def parse(path):
    txt = path.read_text()
    m = re.match(r"^---\n(.*?)\n---\n(.*)$", txt, re.S)
    if not m:
        raise ValueError(f"{path}: no front matter")
    fm = dict(re.findall(r"^(\w+):\s*(.+)$", m.group(1), re.M))
    if re.search(r"^description:\s*[>|]", m.group(1), re.M):
        raise ValueError(f"{path}: description must be one line (folded/multi-line YAML is not parsed)")
    return {"name": fm.get("name", "").strip(), "description": fm.get("description", "").strip(),
            "body": m.group(2).strip(), "path": str(path), "size": len(txt)}


def load():
    out, errors = [], []
    for p in sorted(SKILLS.glob("*/SKILL.md")):
        try:
            s = parse(p)
        except ValueError as e:
            errors.append(str(e))
            continue
        if s["name"] != p.parent.name:
            errors.append(f"{p}: name '{s['name']}' != folder '{p.parent.name}'")
        if not re.fullmatch(r"[a-z0-9-]+", s["name"]):
            errors.append(f"{p}: name must be lowercase letters, digits, hyphens")
        if not s["description"]:
            errors.append(f"{p}: empty description")
        if s["size"] > MAX_CHARS:
            errors.append(f"{p}: {s['size']} chars > {MAX_CHARS} - move detail into a reference file")
        elif s["size"] > TARGET_CHARS:
            print(f"WARN {s['name']}: {s['size']} chars > target {TARGET_CHARS}")
        if len(s["description"]) > MAX_DESC:
            errors.append(f"{p}: description {len(s['description'])} chars > {MAX_DESC}")
        out.append(s)
    return out, errors


def catalog(skills=None):
    """Markdown catalog for system prompts (used by sync_prompts.py). Sorted by name and byte-stable, so the
    prompt prefix (and llama.cpp's prompt cache) only changes when a skill does."""
    skills = sorted(skills or load()[0], key=lambda s: s["name"])
    home = str(pathlib.Path.home())
    rows = [f"Instructions: `{str(SKILLS).replace(home, '~')}/<name>/SKILL.md`."]
    rows += [f"- `/{s['name']}` - {s['description']}" for s in skills]
    return "\n".join(rows)


def write_index(skills):
    lines = ["# Skills index (generated by bin/sync_skills.py - do not edit)", "",
             "| Skill | What it does | Instructions |", "|---|---|---|"]
    for s in skills:
        rel = pathlib.Path(s["path"]).relative_to(REPO)
        lines.append(f"| `/{s['name']}` | {s['description'].replace('|', '/')} | [{rel}]({rel}) |")
    (REPO / "INDEX.md").write_text("\n".join(lines) + "\n")


def sync_webui(skills):
    sys.path.insert(0, str(pathlib.Path.home() / ".config/llama-swap/tools"))
    from sync_prompts import api, webui_token
    import urllib.error
    t = webui_token()
    existing = {s["id"]: s for s in api(t, "GET", "/api/v1/skills/")}
    for s in skills:
        content = (f"{s['body']}\n\n(Source: `{s['path']}` in the local-rig-skills repo; scripts run on this machine "
                   f"with the shell tool.)")
        form = {"id": s["name"], "name": s["name"], "description": s["description"], "content": content,
                "meta": {"tags": [TAG]}, "commit_message": "sync from local-rig-skills"}
        try:
            if s["name"] in existing:
                api(t, "POST", f"/api/v1/skills/id/{s['name']}/update", form)
                print(f"Open WebUI: updated skill {s['name']}")
            else:
                api(t, "POST", "/api/v1/skills/create", form)
                print(f"Open WebUI: created skill {s['name']}")
        except urllib.error.HTTPError as e:
            print(f"Open WebUI: {s['name']} FAILED {e.code} {e.read().decode()[:300]}")
    names = {s["name"] for s in skills}
    for sid, s in existing.items():
        tags = ((s.get("meta") or {}).get("tags") or [])
        if TAG in tags and sid not in names:
            api(t, "DELETE", f"/api/v1/skills/id/{sid}/delete")
            print(f"Open WebUI: removed skill {sid} (no longer in the repo)")
    sync_prompts_menu(t, api, skills)


def sync_prompts_menu(t, api, skills):
    """Typing "/" in the Open WebUI chat box opens the Prompts menu (skills themselves are under "$").
    One prompt per skill (command = skill name) makes "/dow..." autocomplete; picking it inserts "/<skill> "
    and the user types the input after it - the model then runs the skill (see the "# Skills" prompt section)."""
    import urllib.error
    existing = {p["command"].lstrip("/"): p for p in api(t, "GET", "/api/v1/prompts/")}
    for s in skills:
        short = re.split(r" - |\. | \(|, ", s["description"])[0]
        if len(short) > 70:
            short = short[:70].rsplit(" ", 1)[0] + " ..."
        form = {"command": s["name"], "name": f"Skill: {short}", "content": f"/{s['name']} ",
                "tags": [TAG], "meta": {"tags": [TAG]}, "commit_message": "sync from local-rig-skills"}
        p = existing.get(s["name"])
        try:
            if p:
                old_tags = set(p.get("tags") or []) | set(((p.get("meta") or {}).get("tags") or []))
                if (p.get("content") != form["content"] or p.get("name") != form["name"]
                        or old_tags != {TAG}):
                    api(t, "POST", f"/api/v1/prompts/id/{p['id']}/update", form)
                    print(f"Open WebUI: updated /{s['name']} in the prompt menu")
            else:
                api(t, "POST", "/api/v1/prompts/create", form)
                print(f"Open WebUI: added /{s['name']} to the prompt menu")
        except urllib.error.HTTPError as e:
            print(f"Open WebUI prompt /{s['name']}: FAILED {e.code} {e.read().decode()[:300]}")
    names = {s["name"] for s in skills}
    for cmd, p in existing.items():
        if TAG in (p.get("tags") or []) and cmd not in names:
            api(t, "DELETE", f"/api/v1/prompts/id/{p['id']}/delete")
            print(f"Open WebUI: removed /{cmd} from the prompt menu")


if __name__ == "__main__":
    skills, errors = load()
    for e in errors:
        print("ERROR", e)
    print(f"{len(skills)} skills: {', '.join(s['name'] for s in skills)}")
    if errors:
        sys.exit(1)
    if "--check" in sys.argv:
        sys.exit(0)
    write_index(skills)
    print(f"wrote {REPO / 'INDEX.md'}")
    if "--index-only" in sys.argv:
        sys.exit(0)
    sync_webui(skills)
    if "--no-prompts" in sys.argv:
        sys.exit(0)
    r = subprocess.run([sys.executable, str(pathlib.Path.home() / ".config/llama-swap/tools/sync_prompts.py")])
    sys.exit(r.returncode)
